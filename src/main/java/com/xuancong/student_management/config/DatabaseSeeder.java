package com.xuancong.student_management.config;

import com.xuancong.student_management.entity.Company;
import com.xuancong.student_management.entity.Department;
import com.xuancong.student_management.entity.User;
import com.xuancong.student_management.entity.enums.UserRole;
import com.xuancong.student_management.entity.enums.UserStatus;
import com.xuancong.student_management.repository.CompanyRepository;
import com.xuancong.student_management.repository.DepartmentRepository;
import com.xuancong.student_management.repository.UserRepository;
import com.xuancong.student_management.entity.AccessRequest;
import com.xuancong.student_management.entity.FileItem;
import com.xuancong.student_management.entity.Folder;
import com.xuancong.student_management.entity.enums.AccessRequestStatus;
import com.xuancong.student_management.entity.enums.PermissionLevel;
import com.xuancong.student_management.repository.AccessRequestRepository;
import com.xuancong.student_management.repository.FileItemRepository;
import com.xuancong.student_management.repository.FolderRepository;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.boot.CommandLineRunner;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.stereotype.Component;

import javax.sql.DataSource;

@Slf4j
@Component
@RequiredArgsConstructor
public class DatabaseSeeder implements CommandLineRunner {

    private final DataSource dataSource;
    private final UserRepository userRepository;
    private final CompanyRepository companyRepository;
    private final DepartmentRepository departmentRepository;
    private final AccessRequestRepository accessRequestRepository;
    private final FileItemRepository fileItemRepository;
    private final FolderRepository folderRepository;
    private final PasswordEncoder passwordEncoder;

    @Override
    public void run(String... args) {
        try (java.sql.Connection conn = dataSource.getConnection();
             java.sql.Statement stmt = conn.createStatement()) {
            // 1. Ensure latency_ms column exists in chat_messages table
            try {
                stmt.execute("ALTER TABLE chat_messages ADD COLUMN IF NOT EXISTS latency_ms INTEGER");
            } catch (Exception ex) {
                log.debug("Column latency_ms check: {}", ex.getMessage());
            }

            // 2. Ensure new enterprise tables exist
            try {
                stmt.execute("""
                    CREATE TABLE IF NOT EXISTS chat_message_feedbacks (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        message_id BIGINT NOT NULL REFERENCES chat_messages(id) ON DELETE CASCADE,
                        user_id BIGINT NOT NULL REFERENCES users(id),
                        rating VARCHAR(10) NOT NULL,
                        feedback_reason VARCHAR(50),
                        comment TEXT,
                        corrected_answer TEXT,
                        created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
                    );
                    CREATE TABLE IF NOT EXISTS agent_execution_traces (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        message_id BIGINT NOT NULL REFERENCES chat_messages(id) ON DELETE CASCADE,
                        step_order INT NOT NULL,
                        agent_name VARCHAR(50) NOT NULL,
                        action_description TEXT,
                        input_payload TEXT,
                        output_payload TEXT,
                        latency_ms INT,
                        created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
                    );
                    CREATE TABLE IF NOT EXISTS document_chunks (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        file_id BIGINT NOT NULL REFERENCES files(id) ON DELETE CASCADE,
                        chunk_index INT NOT NULL,
                        point_id VARCHAR(64) NOT NULL,
                        content TEXT NOT NULL,
                        token_count INT,
                        page_number INT,
                        content_hash VARCHAR(64),
                        is_active BOOLEAN DEFAULT TRUE,
                        created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
                    );
                    CREATE TABLE IF NOT EXISTS ai_token_usages (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        company_id BIGINT NOT NULL REFERENCES companies(id),
                        department_id BIGINT REFERENCES departments(id),
                        user_id BIGINT NOT NULL REFERENCES users(id),
                        message_id BIGINT REFERENCES chat_messages(id),
                        model_name VARCHAR(50) NOT NULL,
                        prompt_tokens INT NOT NULL,
                        completion_tokens INT NOT NULL,
                        total_tokens INT NOT NULL,
                        cost_usd NUMERIC(10, 6) DEFAULT 0,
                        created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
                    );
                """);
            } catch (Exception ex) {
                log.debug("New enterprise tables creation check: {}", ex.getMessage());
            }

            // 3. Đảm bảo Công ty và Phòng ban mặc định tồn tại
            Company company = companyRepository.findAll().stream().findFirst().orElseGet(() -> {
                Company c = new Company();
                c.setName("Rikai Technology Corporation");
                c.setEmail("contact@rikai.technology");
                c.setPhone("024.3795.8888");
                c.setStorageQuotaGb(100);
                return companyRepository.save(c);
            });

            Department itDept = departmentRepository.findAll().stream().findFirst().orElseGet(() -> {
                Department d = new Department();
                d.setName("Phòng Công Nghệ & Kỹ Thuật AI");
                d.setCompany(company);
                return departmentRepository.save(d);
            });

            // 1. ADMIN
            if (userRepository.findByEmail("admin@enterprise.ai").isEmpty()) {
                User admin = new User();
                admin.setName("Lê Xuân Công (Admin)");
                admin.setEmail("admin@enterprise.ai");
                admin.setPasswordHash(passwordEncoder.encode("admin123"));
                admin.setRole(UserRole.ADMIN);
                admin.setStatus(UserStatus.ACTIVE);
                admin.setCompany(company);
                admin.setDepartment(itDept);
                userRepository.save(admin);
                log.info("-> Đã khởi tạo tài khoản ADMIN: admin@enterprise.ai / admin123");
            }

            // 2. MANAGER
            if (userRepository.findByEmail("manager@enterprise.ai").isEmpty()) {
                User manager = new User();
                manager.setName("Trần Đình Trọng (Manager)");
                manager.setEmail("manager@enterprise.ai");
                manager.setPasswordHash(passwordEncoder.encode("manager123"));
                manager.setRole(UserRole.MANAGER);
                manager.setStatus(UserStatus.ACTIVE);
                manager.setCompany(company);
                manager.setDepartment(itDept);
                userRepository.save(manager);
                log.info("-> Đã khởi tạo tài khoản MANAGER: manager@enterprise.ai / manager123");
            }

            // 3. USER
            if (userRepository.findByEmail("user@enterprise.ai").isEmpty()) {
                User user = new User();
                user.setName("Hoàng Văn Nam (User)");
                user.setEmail("user@enterprise.ai");
                user.setPasswordHash(passwordEncoder.encode("user123"));
                user.setRole(UserRole.USER);
                user.setStatus(UserStatus.ACTIVE);
                user.setCompany(company);
                user.setDepartment(itDept);
                userRepository.save(user);
                log.info("-> Đã khởi tạo tài khoản USER: user@enterprise.ai / user123");
            }

            // 4. Khởi tạo 1 yêu cầu cấp quyền PENDING gửi đến tài khoản Lê Xuân Công (Admin)
            if (accessRequestRepository.findByStatusOrderByCreatedAtDesc(AccessRequestStatus.PENDING).isEmpty()) {
                User requester = userRepository.findByEmail("nam.hv@rikai.technology")
                        .or(() -> userRepository.findByEmail("user@enterprise.ai"))
                        .or(() -> userRepository.findAll().stream().filter(u -> u.getRole() != UserRole.ADMIN).findFirst())
                        .orElse(null);
                FileItem sampleFile = fileItemRepository.findAll().stream().findFirst().orElse(null);
                Folder sampleFolder = folderRepository.findAll().stream().findFirst().orElse(null);

                if (requester != null) {
                    AccessRequest req = AccessRequest.builder()
                            .requester(requester)
                            .folderId(sampleFolder != null ? sampleFolder.getId() : (sampleFile != null && sampleFile.getFolder() != null ? sampleFile.getFolder().getId() : null))
                            .folderName(sampleFolder != null ? sampleFolder.getName() : (sampleFile != null && sampleFile.getFolder() != null ? sampleFile.getFolder().getName() : "Phòng Công Nghệ & Kỹ Thuật AI"))
                            .fileId(sampleFile != null ? sampleFile.getId() : null)
                            .fileName(sampleFile != null ? sampleFile.getName() : "Tai_lieu_Kien_truc_He_thong_RAG_Enterprise_v1.pdf")
                            .reason("Em xin cấp quyền Editor để cập nhật tài liệu kỹ thuật và thiết kế pipeline cho quý 3 ạ.")
                            .requestedLevel(PermissionLevel.EDITOR)
                            .status(AccessRequestStatus.PENDING)
                            .build();
                    accessRequestRepository.save(req);
                    log.info("-> Đã khởi tạo 1 yêu cầu cấp quyền PENDING từ {} gửi cho tài khoản Lê Xuân Công duyệt!", requester.getName());
                }
            }
        } catch (Exception e) {
            log.warn("Database seeder check skipped or error: {}", e.getMessage());
        }
    }
}